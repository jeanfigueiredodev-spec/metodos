let currentLang = 'pt-BR';

function setLanguage(lang) {
    currentLang = lang;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.innerText = translations[lang][key];
        }
    });
}

document.getElementById('lang-select').addEventListener('change', (e) => {
    setLanguage(e.target.value);
});

setLanguage('pt-BR');

// Funcionalidade de Filtro do Blog
function filterBlog(tag, btnElement) {
    document.querySelectorAll('.filter-btn').forEach(btn => btn.classList.remove('active'));
    btnElement.classList.add('active');

    const cards = document.querySelectorAll('.blog-card');
    cards.forEach(card => {
        if (tag === 'all' || card.getAttribute('data-tag') === tag) {
            card.style.display = 'flex';
        } else {
            card.style.display = 'none';
        }
    });
}

// Lógica do Modal do Blog
const modal = document.getElementById("article-modal");

function openModal(articleId) {
    const titleElem = document.getElementById("modal-title");
    const bodyElem = document.getElementById("modal-body");
    
    // Mapear ID para o título correto no idioma atual
    const titleKey = `blog-${articleId.replace('blog', '')}-title`;
    const contentKey = `modal-content-${articleId}`;
    
    if (translations[currentLang][titleKey] && translations[currentLang][contentKey]) {
        titleElem.innerText = translations[currentLang][titleKey];
        bodyElem.innerHTML = translations[currentLang][contentKey];
        modal.classList.add("show");
    }
}

function closeModal() {
    modal.classList.remove("show");
}

// Fechar modal ao clicar fora da caixa branca
window.onclick = function(event) {
    if (event.target == modal) {
        closeModal();
    }
}
